FACE = "\033[1;97m"
SHADOW = "\033[38;5;245m"
RESET = "\033[0m"
FACE_CHARACTERS = frozenset("█▄▀")


def _colourize(line: str) -> str:
    parts: list[str] = []
    active_style = ""
    for character in line:
        style = FACE if character in FACE_CHARACTERS else SHADOW
        if character == " ":
            parts.append(character)
            continue
        if style != active_style:
            parts.append(style)
            active_style = style
        parts.append(character)
    return "".join(parts) + RESET


def render(text: str, use_colour: bool | None = None) -> str:
    safe_text = "".join(
        character if character in FONT else "-" for character in text.upper()[:24]
    )
    glyphs = [FONT[character] for character in safe_text]
    lines = ["".join(glyph[row] for glyph in glyphs).rstrip() for row in range(6)]

    if use_colour is None:
        use_colour = sys.stdout.isatty() and "NO_COLOR" not in os.environ
    if use_colour:
        lines = [_colourize(line) for line in lines]
    return "\n".join(lines)


